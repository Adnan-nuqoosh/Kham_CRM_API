<?php

namespace App\Services;

use Illuminate\Support\Facades\Http;
use Illuminate\Validation\ValidationException;
use RuntimeException;

/**
 * MyFatoorah V3 sandbox adapter. No routes, order mutations or live charges.
 * Calls are disabled unless explicitly enabled with a sandbox token.
 */
final class MyFatoorahV3Client
{
    private const BASE_URL = 'https://apitest.myfatoorah.com/v3';

    private function token(): string
    {
        if (!app()->environment('local', 'testing')
            || !config('commerce.myfatoorah_sandbox_enabled', false)) {
            throw new RuntimeException('MyFatoorah sandbox client is disabled.');
        }

        $token = trim((string) config('commerce.myfatoorah_sandbox_token'));
        if ($token === '') {
            throw new RuntimeException('MyFatoorah sandbox token is not configured.');
        }
        return $token;
    }

    /**
     * Hosted checkout only. The amount and key must be generated by the server
     * from an approved order; never accept them directly from browser input.
     */
    public function createHostedPayment(
        string $amount,
        string $redirectUrl,
        string $idempotencyKey,
        ?string $paymentMethod = null
    ): array {
        if (!preg_match('/^(?:0|[1-9][0-9]{0,10})(?:\.[0-9]{1,4})?$/D', $amount)
            || (float) $amount <= 0) {
            throw ValidationException::withMessages(['amount' => ['Invalid payment amount.']]);
        }
        if (!filter_var($redirectUrl, FILTER_VALIDATE_URL)
            || parse_url($redirectUrl, PHP_URL_SCHEME) !== 'https') {
            throw ValidationException::withMessages(['redirect_url' => ['HTTPS redirect URL required.']]);
        }
        if (!preg_match('/^[A-Za-z0-9_-]{16,128}$/D', $idempotencyKey)) {
            throw ValidationException::withMessages(['idempotency_key' => ['Invalid idempotency key.']]);
        }
        if ($paymentMethod !== null && !in_array($paymentMethod, ['CARD', 'APPLE_PAY', 'GOOGLE_PAY', 'KNET'], true)) {
            throw ValidationException::withMessages(['payment_method' => ['Unsupported payment method.']]);
        }

        $payload = [
            'Order' => ['Amount' => (float) $amount],
            'IntegrationUrls' => ['Redirection' => $redirectUrl],
        ];
        if ($paymentMethod !== null) {
            $payload['PaymentMethod'] = $paymentMethod;
        }

        $response = Http::acceptJson()
            ->withToken($this->token())
            ->withHeaders(['Idempotency-Key' => $idempotencyKey])
            ->timeout(15)->connectTimeout(5)
            ->post(self::BASE_URL . '/payments', $payload);

        if (!$response->successful() || $response->json('IsSuccess') !== true) {
            throw new RuntimeException('MyFatoorah sandbox payment creation failed (HTTP ' . $response->status() . ').');
        }

        $data = $response->json('Data');
        $url = is_array($data) ? ($data['PaymentURL'] ?? null) : null;
        if (!is_string($url) || !filter_var($url, FILTER_VALIDATE_URL)
            || parse_url($url, PHP_URL_SCHEME) !== 'https') {
            throw new RuntimeException('MyFatoorah returned an invalid hosted payment URL.');
        }

        // Webhook matching depends on a valid, persisted provider invoice ID.
        // Never return a payment URL if the invoice cannot be reconciled later.
        $invoiceId = is_array($data) ? ($data['InvoiceId'] ?? null) : null;
        if ((!is_string($invoiceId) && !is_int($invoiceId))
            || !preg_match('/^[0-9]{1,64}$/D', (string) $invoiceId)) {
            throw new RuntimeException('MyFatoorah returned an invalid invoice ID.');
        }

        return [
            'invoice_id' => (string) $invoiceId,
            'payment_url' => $url,
            'payment_completed' => ($data['PaymentCompleted'] ?? null) === true,
        ];
    }

    /**
     * Read-only verification. A successful HTTP response is not proof of payment.
     * Caller must validate invoice, transaction, currency and amount against the
     * stored order before marking anything paid.
     */
    public function getPaymentDetails(string $paymentId): array
    {
        if (!preg_match('/^[0-9]{1,64}$/D', $paymentId)) {
            throw ValidationException::withMessages(['payment_id' => ['Invalid payment ID.']]);
        }

        $response = Http::acceptJson()->withToken($this->token())
            ->timeout(15)->connectTimeout(5)
            ->get(self::BASE_URL . '/payments/' . $paymentId);

        if (!$response->successful() || $response->json('IsSuccess') !== true
            || !is_array($response->json('Data'))) {
            throw new RuntimeException('MyFatoorah sandbox payment enquiry failed (HTTP ' . $response->status() . ').');
        }

        return $response->json('Data');
    }
}
